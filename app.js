        function adjustParticle(type, delta) {
            if (type === 'p') atom.p = Math.max(1, Math.min(12, atom.p + delta));
            if (type === 'n') atom.n = Math.max(0, Math.min(14, atom.n + delta));
            if (type === 'e') atom.e = Math.max(0, Math.min(12, atom.e + delta));
            updateAtomUI();
        }

