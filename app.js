        let currentModuleQuestion = { moduleId: null, index: 0 };

        function startModuleQuestions(moduleId) {
            const questions = moduleQuestions[moduleId];
            if (moduleId > appState.moduleUnlockedThrough) {
                showToast('Beantworte zuerst die Fragen zum aktuellen Modul.', 'info');
                return;
            }
            if (!questions) {
                showToast('Für dieses Modul sind keine Fragen hinterlegt.', 'error');
                return;
            }
            currentModuleQuestion = { moduleId, index: 0 };
            showModuleQuestion();
        }

        function showModuleQuestion() {
            const { moduleId, index } = currentModuleQuestion;
            const questions = moduleQuestions[moduleId];
            const question = questions[index];
            const overlay = document.getElementById('moduleQuestionOverlay');
            const card = document.getElementById('moduleQuestionCard');
            const optionsWrap = document.getElementById('moduleQuestionOptions');
            const feedback = document.getElementById('moduleQuestionFeedback');
            const studyPanel = document.getElementById('moduleQuestionStudy');

            document.getElementById('moduleQuestionProgress').innerText = `Frage ${index + 1} von ${questions.length}`;
            document.getElementById('moduleQuestionTitle').innerText = `Modul ${moduleId}: Wissen prüfen`;
            document.getElementById('moduleQuestionText').innerText = question.question;
            feedback.innerText = '';
            feedback.style.display = 'none';
            feedback.setAttribute('aria-live', 'polite');
            studyPanel.classList.add('hidden');
            optionsWrap.classList.remove('hidden');
            optionsWrap.innerHTML = '';
            card.classList.remove('hidden');
            overlay.classList.remove('hidden');

            const shuffledOptions = question.options.map((option, optionIndex) => ({
                option,
                isCorrect: optionIndex === question.correct
            }));
            for (let index = shuffledOptions.length - 1; index > 0; index--) {
                const swapIndex = Math.floor(Math.random() * (index + 1));
                [shuffledOptions[index], shuffledOptions[swapIndex]] = [shuffledOptions[swapIndex], shuffledOptions[index]];
            }
            currentModuleQuestion.correctIndex = shuffledOptions.findIndex(option => option.isCorrect);

            shuffledOptions.forEach(({ option }, optionIndex) => {
                const button = document.createElement('button');
                button.type = 'button';
                button.className = 'btn atom-question-option';
                button.innerText = option;
                button.addEventListener('click', () => answerModuleQuestion(optionIndex, button));
                optionsWrap.appendChild(button);
            });
        }

        function answerModuleQuestion(selectedIndex, clickedButton) {
            const { moduleId, index } = currentModuleQuestion;
            const questions = moduleQuestions[moduleId];
            const question = questions[index];
            const feedback = document.getElementById('moduleQuestionFeedback');
            const options = document.querySelectorAll('#moduleQuestionOptions .atom-question-option');

            options.forEach(button => {
                button.disabled = true;
            });

            if (selectedIndex === currentModuleQuestion.correctIndex) {
                clickedButton.style.background = 'var(--surface-teal)';
                clickedButton.style.border = '1px solid var(--success)';
                feedback.style.display = 'block';
                feedback.style.color = 'var(--success)';
                feedback.innerText = question.explanation;
                setTimeout(() => {
                    currentModuleQuestion.index += 1;
                    if (currentModuleQuestion.index < questions.length) {
                        showModuleQuestion();
                    } else {
                        document.getElementById('moduleQuestionOverlay').classList.add('hidden');
                        document.getElementById('moduleQuestionCard').classList.add('hidden');
                        completeModule(moduleId);
                    }
                }, 900);
                return;
            }

            clickedButton.style.background = 'var(--surface-error)';
            clickedButton.style.border = '1px solid var(--error)';
            feedback.style.display = 'block';
            feedback.style.color = 'var(--error)';
            feedback.innerText = 'Noch nicht richtig. Lies den passenden Abschnitt und beantworte danach dieselbe Frage noch einmal.';

            const sectionIndex = moduleQuestionStudySectionIndexes[moduleId]?.[index] ?? 0;
            const studySection = moduleDetails[moduleId]?.[sectionIndex];
            document.getElementById('moduleQuestionStudyTitle').innerText = studySection?.title || 'Lies den passenden Abschnitt noch einmal';
            document.getElementById('moduleQuestionStudyText').innerText = studySection?.text || modulesData.find(module => module.id === moduleId).summary;
            document.getElementById('moduleQuestionStudy').classList.remove('hidden');
            document.getElementById('moduleQuestionOptions').classList.add('hidden');
        }

        function retryModuleQuestion() {
            showModuleQuestion();
        }

        function completeModule(id) {
            const unlockedNextModule = id === appState.moduleUnlockedThrough;
            appState.skippedModules = appState.skippedModules.filter(skippedId => skippedId !== id);
            if (!appState.completedModules.includes(id)) {
                appState.completedModules.push(id);
            }
            if (unlockedNextModule) {
                appState.moduleUnlockedThrough = id + 1;
            }
            saveState();
            updateDashboard();
            renderProgress();
            showToast(
                unlockedNextModule
                    ? 'Alle Fragen richtig! Das nächste Modul ist jetzt freigeschaltet.'
                    : 'Alle Fragen richtig beantwortet. Gut wiederholt!',
                'success'
            );
            navigateTo('modules');
        }

        function skipOptionalModule(id) {
            if (!optionalModuleIds.includes(id) || id !== appState.moduleUnlockedThrough) return;
            if (!appState.skippedModules.includes(id)) {
                appState.skippedModules.push(id);
            }
            appState.moduleUnlockedThrough = id + 1;
            saveState();
            updateDashboard();
            renderProgress();
            renderModuleList();
            showToast(`Modul ${id} übersprungen. Du kannst im nächsten Modul weitermachen.`, 'info');
        }

        function restartModules() {
            appState.completedModules = [];
            appState.skippedModules = [];
            appState.moduleUnlockedThrough = 1;
            saveState();
            updateDashboard();
            renderProgress();
            renderModuleList();
            showToast('Die Lernmodule beginnen wieder bei Modul 1.', 'success');
        }

