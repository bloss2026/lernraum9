        function renderSubjectCatalog() {
            const grid = document.getElementById('subjectGrid');
            if (!grid) return;
            grid.innerHTML = '';
            const subjectNavLinks = document.getElementById('subjectNavLinks');
            if (subjectNavLinks) subjectNavLinks.innerHTML = '';
            subjectsData.forEach(subject => {
                if (subjectNavLinks) {
                    const navItem = document.createElement('li');
                    const navButton = document.createElement('button');
                    navButton.className = 'nav-btn subject-nav-btn';
                    navButton.type = 'button';
                    navButton.dataset.subject = subject.id;
                    navButton.textContent = `${subject.icon} ${subject.name}`;
                    navButton.addEventListener('click', () => {
                        openSubject(subject.id);
                        if (window.innerWidth <= 900) sidebar.classList.remove('open');
                    });
                    navItem.appendChild(navButton);
                    subjectNavLinks.appendChild(navItem);
                }

                const card = document.createElement('article');
                card.className = 'subject-card';
                const icon = document.createElement('span');
                icon.className = 'subject-icon';
                icon.setAttribute('aria-hidden', 'true');
                icon.textContent = subject.icon;
                const status = document.createElement('span');
                status.className = `subject-status${subject.available ? ' available' : ''}`;
                status.textContent = subject.available ? 'Inhalte verfügbar' : 'Platzhalter · Inhalte folgen';
                const title = document.createElement('h3');
                title.textContent = subject.name;
                const description = document.createElement('p');
                description.textContent = subject.note || (subject.available
                    ? 'Lernmodule, Experimente und Übungen'
                    : `Noch keine Lerninhalte für ${subject.name} hinterlegt.`);
                const button = document.createElement('button');
                button.className = 'btn';
                button.type = 'button';
                button.textContent = subject.available ? 'Themen ansehen' : 'Fach öffnen';
                button.addEventListener('click', () => openSubject(subject.id));
                card.append(icon, status, title, description, button);
                grid.appendChild(card);
            });
        }

        function openSubject(subjectId) {
            const subject = subjectsData.find(item => item.id === subjectId);
            if (!subject) {
                showToast('Dieses Fach wurde nicht gefunden.', 'error');
                return;
            }
            document.querySelectorAll('.subject-nav-btn').forEach(button => {
                button.classList.toggle('active', button.dataset.subject === subject.id);
            });
            renderSubjectPage(subject);
            navigateTo('subjectPage');
        }

